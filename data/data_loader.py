class Dataset_Custom(Dataset):
    def __init__(self, graph,root_path, flag='train', size=None,
                 features='S', data_path='WTH.csv',
                 target='OT', scale=True, inverse=False, timeenc=0, freq='h', cols=None):
        # size [seq_len, label_len, pred_len]
        # info
        self.graph = graph
        if size == None:
            self.seq_len = 24*4*4
            self.label_len = 24*4
            self.pred_len = 24*4
        else:
            self.seq_len = size[0]          #预测长度96         encoder对96个做编码
            self.label_len = size[1]        #标签长度48
            self.pred_len = size[2]         #预测长度24         decoder对72个做编码
        # init

        assert flag in ['train', 'test', 'val']
        type_map = {'train':0, 'val':1, 'test':2}
        self.set_type = type_map[flag]
        
        self.features = features            #数据集所有列（多变量）
        self.target = target                #标签列（预测的数据）
        self.scale = scale
        #if flag == 'test':
            #self.scale = False
        self.inverse = inverse
        self.timeenc = timeenc
        self.freq = freq
        self.cols=cols
        self.root_path = root_path
        self.data_path = data_path
        self.__read_data__()

    def __read_data__(self):                    #处理时间数据
        self.scaler = StandardScaler()          #数据标准化（归一化）
        df_raw = pd.read_csv(os.path.join(self.root_path,
                                          self.data_path))
        Wind_fp = './data/Wind.npy'
        wind_raw = np.array(np.load(Wind_fp))   #11688,10,2
        u = wind_raw[:,:, 0] * units.meter / units.second #feature第三维的倒数第二数据计算出u方向风速
        v = wind_raw[:,:, 1] * units.meter / units.second #feature第三维的倒数第一数据计算出v方向风速
        speed = 3.6 * mpcalc.wind_speed(u, v)._magnitude #计算出speed
        direc = mpcalc.wind_direction(u, v)._magnitude   #计算出derection

        '''
        df_raw.columns: ['date', ...(other features), target feature]
        '''
        # cols = list(df_raw.columns); 
        if self.cols:
            cols=self.cols.copy()
            cols.remove(self.target)
        else:
            cols = list(df_raw.columns); cols.remove(self.target); cols.remove('date')      #取出特征列名字
        df_raw = df_raw[['date']+cols+[self.target]]    #整个数据集分为：时间+特征+标签

        num_train = int(len(df_raw)*0.8)        #训练测试验证7：2：1
        num_test = int(len(df_raw)*0.1)
        num_vali = len(df_raw) - num_train - num_test
        border1s = [0, num_train-self.seq_len, len(df_raw)-num_test-self.seq_len]
        border2s = [num_train, num_train+num_vali, len(df_raw)]
        border1 = border1s[self.set_type]       #设定训练、验证、测试集边界
        border2 = border2s[self.set_type]
        
        if self.features=='M' or self.features=='MS':
            cols_data = df_raw.columns[1:]
            df_data = df_raw[cols_data]
        elif self.features=='S':
            df_data = df_raw[[self.target]]

        if self.scale:                          #数据标准化
            train_data = df_data[border1s[0]:border2s[0]]
            self.scaler.fit(train_data.values)
            # data = np.expand_dims(self.scaler.transform(df_data.values),axis=-1)
            # speed = np.expand_dims(self.scaler.transform(speed),axis=-1)
            # direc = np.expand_dims(self.scaler.transform(direc),axis=-1)
            data = self.scaler.transform(df_data.values)
            speed = self.scaler.transform(speed)
            direc = self.scaler.transform(direc)
            data = np.concatenate([data[:, :, None],speed[:, :, None], direc[:, :, None]], axis=-1)  # 在featrue数组最后添加以上特征
        else:
            data = df_data.values
            
        df_stamp = df_raw[['date']][border1:border2]        #取出时间列
        df_stamp['date'] = pd.to_datetime(df_stamp.date)    #转换格式
        data_stamp = time_features(df_stamp, timeenc=self.timeenc, freq=self.freq)

        self.data_x = data[border1:border2]
        if self.inverse:
            self.data_y = df_data.values[border1:border2]
        else:
            self.data_y = data[border1:border2]
        self.data_stamp = data_stamp
    
    def __getitem__(self, index):
        s_begin = index                             #随机传入索引为起始位置
        s_end = s_begin + self.seq_len
        r_begin = s_end - self.label_len
        r_end = r_begin + self.label_len + self.pred_len

        seq_x = self.data_x[s_begin:s_end]          #（96，12）：96序列长度，每个序列12个向量
        if self.inverse:
            seq_y = np.concatenate([self.data_x[r_begin:r_begin+self.label_len], self.data_y[r_begin+self.label_len:r_end]], 0)
        else:
            seq_y = self.data_y[r_begin:r_end]      #（72，12）
        seq_x_mark = self.data_stamp[s_begin:s_end] #（96，4）：4个时间特征
        seq_y_mark = self.data_stamp[r_begin:r_end] #（72,4）

        return seq_x, seq_y, seq_x_mark, seq_y_mark
    
    def __len__(self):
        return len(self.data_x) - self.seq_len- self.pred_len + 1

    def inverse_transform(self, data):
        return self.scaler.inverse_transform(data)

class Dataset_Pred(Dataset):
    def __init__(self,root_path, flag='pred', size=None,
                 features='S', data_path='ETTh1.csv', 
                 target='OT', scale=True, inverse=False, timeenc=0, freq='15min', cols=None):
        # size [seq_len, label_len, pred_len]
        # info
        if size == None:
            self.seq_len = 24*4*4
            self.label_len = 24*4
            self.pred_len = 24*4
        else:
            self.seq_len = size[0]
            self.label_len = size[1]
            self.pred_len = size[2]
        # init
        assert flag in ['pred']
        
        self.features = features
        self.target = target
        self.scale = scale
        self.inverse = inverse
        self.timeenc = timeenc
        self.freq = freq
        self.cols=cols
        self.root_path = root_path
        self.data_path = data_path
        self.__read_data__()

    def __read_data__(self):
        self.scaler = StandardScaler()
        df_raw = pd.read_csv(os.path.join(self.root_path,
                                          self.data_path))
        '''
        df_raw.columns: ['date', ...(other features), target feature]
        '''
        if self.cols:
            cols=self.cols.copy()
            cols.remove(self.target)
        else:
            cols = list(df_raw.columns); cols.remove(self.target); cols.remove('date')
        df_raw = df_raw[['date']+cols+[self.target]]
        
        border1 = len(df_raw)-self.seq_len
        border2 = len(df_raw)
        
        if self.features=='M' or self.features=='MS':
            cols_data = df_raw.columns[1:]
            df_data = df_raw[cols_data]
        elif self.features=='S':
            df_data = df_raw[[self.target]]

        if self.scale:
            self.scaler.fit(df_data.values)
            data = self.scaler.transform(df_data.values)
        else:
            data = df_data.values
            
        tmp_stamp = df_raw[['date']][border1:border2]
        tmp_stamp['date'] = pd.to_datetime(tmp_stamp.date)
        pred_dates = pd.date_range(tmp_stamp.date.values[-1], periods=self.pred_len+1, freq=self.freq)
        
        df_stamp = pd.DataFrame(columns = ['date'])
        df_stamp.date = list(tmp_stamp.date.values) + list(pred_dates[1:])
        data_stamp = time_features(df_stamp, timeenc=self.timeenc, freq=self.freq[-1:])

        self.data_x = data[border1:border2]
        if self.inverse:
            self.data_y = df_data.values[border1:border2]
        else:
            self.data_y = data[border1:border2]
        self.data_stamp = data_stamp
    
    def __getitem__(self, index):
        s_begin = index
        s_end = s_begin + self.seq_len
        r_begin = s_end - self.label_len
        r_end = r_begin + self.label_len + self.pred_len

        seq_x = self.data_x[s_begin:s_end]
        if self.inverse:
            seq_y = self.data_x[r_begin:r_begin+self.label_len]
        else:
            seq_y = self.data_y[r_begin:r_begin+self.label_len]
        seq_x_mark = self.data_stamp[s_begin:s_end]
        seq_y_mark = self.data_stamp[r_begin:r_end]

        return seq_x, seq_y, seq_x_mark, seq_y_mark
    
    def __len__(self):
        return len(self.data_x) - self.seq_len + 1

    def inverse_transform(self, data):
        return self.scaler.inverse_transform(data)
